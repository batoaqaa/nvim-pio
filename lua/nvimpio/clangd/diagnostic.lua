local M = {}
-- ====================================================================
-- HELPERS FOR STRUCTURAL FILE INJECTION
-- ====================================================================
local local_clangd_file = vim.fn.getcwd() .. '/.clangd'

local function ensure_baseline_template()
  local f_check = io.open(local_clangd_file, 'r')
  if not f_check then
    local f_init = io.open(local_clangd_file, 'wb')
    if f_init then
      local baseline_template = [[
CompileFlags:
  Remove: []
  Add:
    [
      "-xc++",
      "-std=gnu++17",
      "-Wno-unknown-argument",
      "-Wno-macro-redefined",
      "-Wno-invalid-token-paste",
      "-Wno-typedef-redefinition",
      "-Wno-unknown-attributes",
      "-Wno-pragma-system-header-outside-header",
      "-Wno-unknown-warning-option",
      "-Wno-unused-includes",
    ]
Diagnostics:
  Suppress:
    [
      "macro_too_many_args",
      "unused_macro_definition",
      "pp_file_not_found",
      "pp_file_not_found_angled_not_fatal",
      "pp_included_file_not_found",
      "pp_including_mainfile_in_preamble",
      "unused-includes",
      "misc-definitions-in-headers",
    ]
  ClangTidy:
    Remove: ["readability-*", "modernize-*", "bugprone-*", "cert-err58-cpp"]

---
# Dynamic configuration block generated by nvim-pio
CompileFlags:
  Remove: [
    "-mlongcalls",
    "-fstrict-volatile-bitfields",
    "-fno-tree-switch-conversion"
    ]
]]
      f_init:write(baseline_template)
      f_init:close()
    end
  else
    f_check:close()
  end
end

local function inject_into_clangd(code, message)
  ensure_baseline_template()

  local file_content = ''
  local f_read = io.open(local_clangd_file, 'rb')
  if f_read then
    file_content = f_read:read('*all')
    f_read:close()
  end

  local target_item = ''
  local is_driver_flag = string.match(tostring(code):lower(), '^drv_')
    or string.match(message:lower(), 'unknown argument')
    or string.match(message:lower(), '%-mlongcalls')

  if is_driver_flag then
    local extracted_flag = string.match(message, '[\'"](%-.-)[\'"]') or string.match(message, '%s(%-.*)%s')
    if not extracted_flag then
      extracted_flag = string.match(message, 'argument%s+(%-.*)$') or '-mlongcalls'
    end
    target_item = vim.trim(extracted_flag):gsub('[\',;"%s]', '')
  else
    target_item = code
  end

  if not target_item or target_item == '' or target_item == 'uncategorized_noise' then
    return false
  end

  -- Wrap in double quotes for driver flags to ensure exact lookup validation entries match
  local search_signature = is_driver_flag and ('"' .. target_item .. '"') or target_item
  if string.find(file_content, search_signature, 1, true) then
    return false -- Already mapped
  end

  local sep_marker = '# Dynamic configuration block generated by nvim-pio'
  local sections = vim.split(file_content, sep_marker, { plain = true })

  local base_part = sections[1] or ''
  local dynamic_part = sections[2] or ''
  local updated_dynamic = ''

  if is_driver_flag then
    -- Escape pattern symbols to protect string replacement fields
    local pattern = '(CompileFlags:%s*\n%s*Remove:%s*%[)'
    local replacement = 'CompileFlags:\n  Remove: [\n    "' .. target_item .. '",'
    updated_dynamic = string.gsub(dynamic_part, pattern, replacement)
  else
    if string.find(dynamic_part, 'Diagnostics:%s*\n%s*Suppress:%s*%[') then
      local pattern = '(Diagnostics:%s*\n%s*Suppress:%s*%[)'
      local replacement = 'Diagnostics:\n  Suppress: [\n    ' .. target_item .. ','
      updated_dynamic = string.gsub(dynamic_part, pattern, replacement)
    else
      updated_dynamic = dynamic_part .. '\n\nDiagnostics:\n  Suppress: [\n    ' .. target_item .. ',\n  ]'
    end
  end

  local final_content = base_part .. sep_marker .. updated_dynamic
  local f_write = io.open(local_clangd_file, 'wb')
  if f_write then
    f_write:write(final_content)
    f_write:close()
  end
  return true
end

-- ====================================================================
-- 3. THE GROUPED INTERACTIVE SELECTION ENGINE
-- ====================================================================
function M.manage_file_diagnostics_interactive()
  local current_buf = vim.api.nvim_get_current_buf()
  local diagnostics = vim.diagnostic.get(current_buf)

  if #diagnostics == 0 then
    vim.notify('✅ No active LSP diagnostics found in this file!', vim.log.levels.INFO)
    return
  end

  local groups = {}
  local group_names = {}

  for _, diag in ipairs(diagnostics) do
    local group_key = diag.code or 'uncategorized_noise'
    if not groups[group_key] then
      groups[group_key] = {}
      table.insert(group_names, group_key)
    end
    table.insert(groups[group_key], diag)
  end

  vim.ui.select(group_names, {
    prompt = ' 📂 Select an Error Group Type to Manage ',
    format_item = function(code)
      return string.format('Group [%s] — (%d active instances found)', code, #groups[code])
    end,
  }, function(selected_group)
    if not selected_group then
      return
    end

    local group_diagnostics = groups[selected_group]
    local options = {
      '💥 Suppress ALL errors inside group [' .. selected_group .. ']',
      '🔍 Inspect and pick specific instances one by one',
    }

    vim.ui.select(options, {
      prompt = ' Action for group [' .. selected_group .. '] ',
    }, function(action_choice)
      if not action_choice then
        return
      end

      -- 🌟 THE CRITICAL CONDITIONAL REPAIR: Check explicitly against array index 1
      if action_choice == options[1] then
        local total_added = 0
        for _, diag in ipairs(group_diagnostics) do
          local actual_code = diag.code or selected_group
          if inject_into_clangd(actual_code, diag.message) then
            total_added = total_added + 1
          end
        end

        if total_added > 0 then
          vim.notify(
            '✅ Bulk action complete! Added ' .. total_added .. ' suppressions to .clangd',
            vim.log.levels.WARN,
            { title = 'Project .clangd Mangler' }
          )
          require('nvimpio.clangd.control').restart()
        else
          vim.notify('ℹ All items in group are already fully suppressed.', vim.log.levels.INFO)
        end
      else
        local individual_items = {}
        for _, diag in ipairs(group_diagnostics) do
          table.insert(individual_items, {
            code = diag.code or selected_group,
            message = diag.message,
            line = diag.lnum + 1,
          })
        end

        vim.ui.select(individual_items, {
          prompt = ' 🛠 Select exact single instance line item to ignore ',
          format_item = function(item)
            return string.format('Line %d: %s', item.line, item.message:sub(1, 65) .. '...')
          end,
        }, function(final_choice)
          if not final_choice then
            return
          end

          if inject_into_clangd(final_choice.code, final_choice.message) then
            local is_driver = string.match(tostring(final_choice.code):lower(), '^drv_') or string.match(final_choice.message:lower(), 'unknown argument')
            local msg = is_driver and 'Stripped matching toolchain argument!' or 'Suppressed diagnostic code globally!'
            vim.notify('✅ ' .. msg, vim.log.levels.WARN, { title = 'Project .clangd Mangler' })
            require('nvimpio.clangd.control').restart()
          else
            vim.notify('ℹ Item is already handled inside configuration profiles.', vim.log.levels.INFO)
          end
        end)
      end
    end)
  end)
end

return M
