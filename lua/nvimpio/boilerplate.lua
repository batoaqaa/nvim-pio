boilerplate['.clangd'] = {
  -- content = [[
  static = [[
---
CompileFlags:
  Remove: [
    ]
  Add:  [
    ]
Diagnostics:
  Suppress:  [
    ]
  ClangTidy:
    Remove: ["readability-*", "modernize-*", "bugprone-*", "cert-err58-cpp"]
]],

  dynamic = [[
---
# Dynamic configuration block generated by nvim-pio
PathMappings:
  %s

CompileFlags:
  Remove: [
    %s
    ]
  Add: [
    %s
    ]
]],
  --"drv_unknown_argument",
  content = function(self)
    local core = require('nvimpio')
    local cwdClangd = vim.fs.joinpath(vim.uv.cwd(), '.clangd')
    local coreClangd = vim.fs.joinpath(core.config.pio_storage_dir, '.clangd')
    local staticBlock, dynamicBlock = '', ''

    if vim.uv.fs_stat(cwdClangd) then
      local ok, content = misc.readFile(cwdClangd)

      if not ok or not content then
        return nil
      end

      -- Strip out any previous dynamic blocks to prevent endless growing
      if ok then
        staticBlock = content:gsub('\n%-%-%-\n# Dynamic configuration block generated by nvim%-pio.*', '')
      end
    else
      staticBlock = self.static
    end

    -- 1. Format the removed compiler flags
    -- local removed_args = {}
    -- for _, flag in ipairs(M.remove or {}) do
    --   table.insert(removed_args, string.format('%q', flag))
    -- end
    -- 1. 🟢 SINGLE-SOURCE HYDRODYNAMIC SYNC:
    -- Dynamically generate the removals list straight out of your master dictionary map!
    local removed_args = {}
    local success, pio_diag = pcall(require, 'nvimpio.clangd.diagnostic')

    if success and pio_diag and pio_diag.removed_flags then
      for flag, is_blocked in pairs(pio_diag.removed_flags) do
        if is_blocked and type(flag) == 'string' and flag ~= '' then
          table.insert(removed_args, string.format('%q', flag))
        end
      end
      -- Sort the flags so your physical .clangd file remains beautifully clean and alphabetical
      table.sort(removed_args)
    end

    -- 2. 🟢 UNIFIED ADD MODULE: Collects both compiler macros and include paths
    local added_flags = {}
    do
      if _G.metadata then
        -- First, append your auto-discovered board macro defines cleanly (-D__XTENSA__=1, etc.)
        if type(_G.metadata.auto_defines) == 'table' then
          for _, define in ipairs(_G.metadata.auto_defines) do
            if type(define) == 'string' and define ~= '' then
              table.insert(added_flags, string.format('%q', define))
            end
          end
        end

        -- Second, append all pre-sorted include path flags (-I and -isystem)
        local include_pools = {
          _G.metadata.includes_build,
          _G.metadata.includes_toolchain,
          _G.metadata.includes_compatlib,
        }

        for _, pool in ipairs(include_pools) do
          for _, raw_flag in ipairs(pool or {}) do
            if type(raw_flag) == 'string' and raw_flag ~= '' then
              -- Safely normalize trailing splay slashes and wrap as YAML literal strings
              table.insert(added_flags, string.format('%q', vim.fs.normalize(raw_flag)))
            end
          end
        end
      end
    end

    -- 3. 🟢 UNIFIED ADD MODULE: Collects both compiler macros and include paths
    local libpaths = {}
    do
      if _G.metadata then
        -- First, append your auto-discovered board macro defines cleanly (-D__XTENSA__=1, etc.)
        if type(_G.metadata.libsource_dirs) == 'table' then
          for i, path in ipairs(_G.metadata.libsource_dirs) do
            if type(path) == 'string' and path ~= '' then
              table.insert(libpaths, string.format('%q: %q', path, '${path' .. i .. '}'))
            end
          end
        end
      end
    end

    -- Assemble the dynamic block using native string.format insertions
    dynamicBlock = string.format(self.dynamic, table.concat(libpaths, ',\n  '), table.concat(removed_args, ',\n    '), table.concat(added_flags, ',\n    '))

    local final_content = staticBlock .. '\n' .. dynamicBlock

    -- 1. Read the old content from disk to check if an update actually happened
    local has_changed = true
    local read_ok, old_content = misc.readFile(cwdClangd)
    if read_ok and old_content == final_content then
      has_changed = false -- Content is identical, skip writing and restarting!
    end

    if has_changed then
      misc.writeFile(cwdClangd, final_content, {})
      misc.writeFile(coreClangd, final_content, {})

      -- 🟢 RIGID TYPE-SAFE RELOAD ROUTINE:
      vim.schedule(function()
        local active_clients = vim.lsp.get_clients({ name = 'clangd' })
        local should_restart = false

        for _, client in ipairs(active_clients) do
          -- Verify client is valid and the notify method exists natively
          if client and type(client.notify) == 'function' then
            -- It takes exactly 2 arguments (method, params). It is structurally
            -- simpler and completely satisfies lua-ls's strict type verification checks!
            client:notify('workspace/didChangeConfiguration', { settings = {} })
            should_restart = true
          end
        end

        -- Execute the restart cleanly outside the iterator loop block
        if should_restart then
          vim.notify('nvimpio: Toolchain configurations updated. Reloading workspace...', vim.log.levels.INFO)
          require('nvimpio.clangd.control').restart()
          -- vim.cmd("silent! LspRestart clangd")
        end
      end)
    end

    return final_content
  end,
}

