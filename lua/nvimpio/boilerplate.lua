-- "-DCORE_MOCK", add
-- "-ferror-limit=0", add
-- "macro_too_many_args", suppress
boilerplate['.clangd'] = {
  static = [[
---
CompileFlags:
  Remove: [
    "-fipa-pta.*",
    ]
  Add:  [
    "-xc++",
    "-std=gnu++17",
    "-ferror-limit=0",  # FORCE CLANGD TO PARSE EVERY ERROR IN ONE PASS
    ]
Diagnostics:
  Suppress:  [
    ]
  ClangTidy:
    Remove: ["readability-*", "modernize-*", "bugprone-*", "cert-err58-cpp"]
]],

  dynamic = [[
---
# Dynamic configuration block generated by nvim-pio
CompileFlags:
  Remove: [
%s
    ]
Diagnostics:
  Suppress:  [
%s
  ]
]],

  content = function(self)
    -- Safe dynamic resolution of external utilities modules
    local core = require('nvimpio')

    local cwdClangd = misc.joinPath(vim.uv.cwd(), '.clangd')
    local coreClangd = misc.joinPath(core.config.pio_storage_dir, '.clangd')
    local staticBlock, dynamicBlock = '', ''

    -- 1. Determine baseline content
    if vim.uv.fs_stat(cwdClangd) then
      local ok, content = misc.readFile(cwdClangd)
      if ok and content then
        -- Clean existing dynamic traces to prevent file growth loops
        staticBlock = content:gsub('\n%-%-%-\n# Dynamic configuration block generated by nvim%-pio.*', '')
      else
        staticBlock = self.static
      end
    else
      staticBlock = self.static
    end

    -- 2. Format tables arrays cleanly with uniform spacing and double quotes
    local formatted_remove = {}
    for _, flag in ipairs(M.remove or {}) do
      table.insert(formatted_remove, string.format('    "%s"', flag))
    end

    local formatted_suppress = {}
    for _, code in ipairs(M.suppress or {}) do
      table.insert(formatted_suppress, string.format('    "%s"', code))
    end

    -- 3. Construct the dynamic string payload using clean formatting separators
    local flags_str = table.concat(formatted_remove, ',\n')
    local codes_str = table.concat(formatted_suppress, ',\n')
    dynamicBlock = string.format(self.dynamic, flags_str, codes_str)

    local final_content = staticBlock:gsub('%s+$', '') .. '\n' .. dynamicBlock

    -- 4. Sync configuration adjustments out to both destination layers
    misc.writeFile(cwdClangd, final_content, {})
    if core.config.pio_storage_dir and core.config.pio_storage_dir ~= '' then
      misc.writeFile(coreClangd, final_content, {})
    end

    return final_content
  end,
}
